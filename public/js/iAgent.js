const URL_PROXY = `${window.location.origin}/api/client`;

export default class IAgent {

    constructor() {}

    // Private function responsible for displaying the screen with the error message and clearing sessionStorage
    #errorHandler = async (message) => {
        sessionStorage.clear();
        window.location.href = `/force-error?msg=${encodeURIComponent(message)}`;
        return;
    };

    async initAgent(key, mode) {

        try {

            // fetch request to the local server to hide the IP and port of the intelligence agent
            const response = await fetch(`${URL_PROXY}/init-agent`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ mode })
            });

            // An error occurred at an earlier stage; we handle the error by passing the full message to the catch block
            if (!response.ok) {
                const error = await response.json();
                throw new Error(error.error + " : " + error.details)
            }   

            // returns the key generated by the local server
            const data = await response.json();

            // the key is stored in sessionStorage
            sessionStorage.setItem(key, data.sessionId);

            // we return the sessionId
            return data.sessionId;

        } catch (error) {
            this.#errorHandler(error.message);
        }
    }


    async createCustomModel(id, modelName, from, system, parameters) {

        try {

            // fetch request to the local server to hide the IP and port of the intelligence agent
            const response = await fetch(`${URL_PROXY}/create-custom-model`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ sessionId: id, modelName, from, system, parameters })
            });

            // An error occurred at an earlier stage; we handle the error by passing the full message to the catch block
            if (!response.ok) {
                const error = await response.json();
                throw new Error(error.error + " : " + error.details)
            }   

            return await response.json();

        } catch (error) {
            this.#errorHandler(error.message);
        }
    }


    async fixModelSystem(id, system, parameters) {
        try {

            // fetch request to the local server to hide the IP and port of the intelligence agent
            const response = await fetch(`${URL_PROXY}/fix-model-system`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ sessionId: id, system, parameters })
            });

            // An error occurred at an earlier stage; we handle the error by passing the full message to the catch block
            if (!response.ok) {
                const error = await response.json();
                throw new Error(error.error + " : " + error.details)
            }   

            return await response.json();

        } catch (error) {
            this.#errorHandler(error.message);
        }   
    }


    async sendMessage(id, text, typeText = 'chat', promptWrapperText = '', modelText = '') {

        try {

             // fetch request to the local server to hide the IP and port of the intelligence agent
            const response = await fetch(`${URL_PROXY}/send-message`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    sessionId: id,
                    message: text,
                    type: typeText,
                    promptWrapper: promptWrapperText,
                    model: modelText
                })
            });

            // An error occurred at an earlier stage; we handle the error by passing the full message to the catch block
            if (!response.ok) {
                const error = await response.json();
                throw new Error(error.error + " : " + error.details)
            }   

            // we return the answer
            const data = await response.json();
            return data.answer;

        } catch (error) {
            this.#errorHandler(error.message);
        }
    }
}